 const userRequest={username:'reviewer',password:'short',role:'user',active:true,typeIds:[type]};
 const invalidPassword=await call('/admin/users',userRequest,ac);
 assert.equal(invalidPassword.status,400);assert.match(invalidPassword.data.error,/8–256/);
 const missingName=await call('/admin/users',{...userRequest,username:'',password:'password123'},ac);
 assert.equal(missingName.status,400);assert.match(missingName.data.error,/Username is required/);
 assert.equal((await call('/admin/users',null,ac)).data.length,1);
 const user=(await call('/admin/users',{username:'reviewer',password:'password123',role:'user',active:true,typeIds:[type]},ac)).data.id;
 const duplicate=await call('/admin/users',{...userRequest,password:'password123'},ac);
 assert.equal(duplicate.status,409);assert.match(duplicate.data.error,/already exists/);
 const unchangedPassword=await call('/admin/users',{...userRequest,id:user,password:''},ac);
 assert.equal(unchangedPassword.status,200);
 const uc=(await call('/login',{username:'reviewer',password:'password123'})).cookie;
 assert.equal((await call('/projects',null,uc)).data.length,0);
 assert.equal((await call('/projects/nexora-software/documents',null,uc)).status,403);
 assert.equal((await call('/admin/settings',null,uc)).status,403);
 const created=await call('/projects',{company:'Test project'},uc);
 assert.equal(created.status,201);const pid=created.data.id;
 assert.equal((await call('/projects',{company:'',typeId:type},uc)).status,400);
 assert.equal(db.prepare('SELECT type_id FROM projects WHERE id=?').get(pid).type_id,null);
 assert.equal((await call(`/projects/${pid}/analyses`,{skillId:'investment'},uc)).status,403);
 assert.equal((await call(`/projects/${pid}/analyses`,{skillId:type},uc)).status,400);
 assert.equal((await call(`/projects/${pid}/analyses`,{},uc)).status,400);
 const did=(await call(`/projects/${pid}/documents`,{title:'Evidence',markdown:'# Source\nVerified content'},uc)).data.id;
 // Read a recorded real analysis through the API without starting an AI job.
 const fixture=JSON.parse(await fs.readFile(new URL('./fixtures/revenue-review.json',import.meta.url),'utf8'));
 const snapshot={...fixture.snapshot,project:{id:pid,company:'Test project'},settings:{agent:'codex',models:{codex:'gpt-6-luna'},efforts:{}}};
 db.prepare('INSERT INTO runs VALUES(?,?,?,?,?,?,?)').run('recorded-review',pid,'2026-10-07T00:00:00.000Z','completed',JSON.stringify(snapshot),JSON.stringify(fixture.report),null);
 const saved=(await call(`/projects/${pid}/analyses/recorded-review`,null,uc)).data.result;assert.equal(saved.format,'markdown');assert.equal(saved.sections.length,9);assert.ok(saved.sections[0].html.includes('data-citation'));assert.ok(saved.markdown.includes(fixture.report.sections[0].items[0].statement));
 await call('/admin/types',{id:type,name:'Technical review',criteria:'Updated criterion',playbook:'Updated playbook'},ac);
 db.prepare('UPDATE documents SET markdown=? WHERE id=?').run('Changed current evidence',did);
 const archived=(await call(`/projects/${pid}/analyses/recorded-review`,null,uc)).data;
 assert.deepEqual(archived.snapshot.documents.map(({html,...d})=>d),fixture.snapshot.documents);
 assert.match(archived.snapshot.documents[0].html,/<h1/);
 assert.ok(Object.values(archived.result.citations).every(c=>c.html));
 assert.equal(archived.snapshot.type.criteria,fixture.snapshot.type.criteria);
 assert.equal((await call('/admin/settings',{agent:'codex',model:'gpt-6-luna'},ac)).status,200);
 assert.equal((await call('/admin/settings',null,ac)).data.agent,'codex');
 // Both archive listing and direct archived URLs obey type visibility.
 assert.equal((await call(`/projects/${pid}/archive`,{archived:true},uc)).status,403);
 assert.equal((await call(`/projects/${pid}/archive`,{archived:'yes'},ac)).status,400);
 assert.equal((await call(`/projects/${pid}/archive`,{archived:true},ac)).status,200);
 assert.equal((await call('/projects',null,uc)).data.length,0);
 assert.deepEqual((await call('/projects?archived=1',null,uc)).data.map(p=>p.id),[pid]);
 assert.equal((await call(`/projects/${pid}/documents`,null,uc)).status,200);
