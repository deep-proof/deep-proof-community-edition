 async function call(p,b,cookie='',method){const r=await fetch(base+'/api'+p,{method:method||(b?'POST':'GET'),headers:{'content-type':'application/json',cookie},...(b?{body:JSON.stringify(b)}:{})});return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};}
 assert.deepEqual((await call('/me')).data,null);
 assert.equal((await call('/me')).status,200);
 assert.equal((await call('/projects')).status,401);
 const admin=await call('/login',{username:'admin',password:'admin'});assert.equal(admin.status,200);let ac=admin.cookie;
